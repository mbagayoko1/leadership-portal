// Pulls the selected playlists of advanced-level French channels, keeps only
// each channel's own videos, leaves out partisan politics, gives each video
// ONE theme, and writes src/frenchVideos.js for the "Polish Your French"
// module.
//
//   npm run pull:french
//
// A video's theme comes from its title when a rule matches, otherwise from
// the playlist it was found in. Titles and durations are stored as published;
// nothing else from the videos is copied. Each playlist page lists at most
// its first 100 videos.
import { FR_CHANNELS, FR_PLAYLISTS } from "../src/frenchSources.js";
import { playlistVideos, playlistUrl, writeLibrary } from "./lib/youtube.mjs";

const OUT = new URL("../src/frenchVideos.js", import.meta.url);
const EXCLUDE = /élection|electoral|présidentielle|presidential|macron|le pen|mélenchon|zemmour|trump|kamala|partisan/i;

// First matching rule wins; otherwise the playlist's theme.
const RULES = [
  ["exams", /\b(DELF|DALF|TCF|TEF)\b/],
  ["errors", /faute|mistake|erreur|never say|ne dites (plus|pas)|ne faites plus|don't say|incorrect|à ne pas dire/i],
  ["writing", /e-?mail|courriel|\blettre\b|écrire|writing|dictée|dictation|orthographe|spelling/i],
  ["pronunciation", /prononc|pronunc|pronounc|\baccents?\b|liaison|nasal|sounds?\b|\bsons?\b/i],
  ["grammar", /grammaire|grammar|subjonctif|subjunctive|conjug|passé composé|imparfait|plus-que-parfait|conditionnel|pronom|pronouns?\b|\baccords?\b|\btenses?\b/i],
  ["familiar", /familier|argot|slang|verlan|gros mots|swear/i],
  ["expressions", /expression|idiom|proverbe/i],
  ["culture", /cultur|custom|coutume|politesse|bise|tutoy|vouvoy|\btu ou vous\b|gestes|gestures|étiquette|savoir-vivre/i],
  ["listening", /interview|conversation|podcast|dialogue|listening|comprendre les français|understand (the )?french|écoute/i],
  ["learning", /comment apprendre|how to learn|conseils? pour|astuces? pour|méthode|progresser|sans bloquer|parler couramment|speak fluently|motivation/i]
];
const FR_THEME_KEYS = ["learning", "pronunciation", "grammar", "errors", "vocab", "expressions", "writing", "culture", "listening", "familiar", "exams"];

const clean = t => t.normalize("NFC").replace(/\s*#shorts\s*/gi, " ").replace(/\s+/g, " ").trim();
const seen = new Map(), left = [];
for (const pl of FR_PLAYLISTS) {
  const owner = FR_CHANNELS[pl.c].name;
  const list = await playlistVideos(playlistUrl(pl.id), owner);
  for (const v of list) {
    if (seen.has(v.id)) continue;
    if (!v.by) throw new Error("No channel name for " + v.id + "; YouTube may have changed its page.");
    if (v.by !== owner) { left.push(`other channel (${v.by}): ${v.t}`); seen.set(v.id, null); continue; }
    if (EXCLUDE.test(v.t)) { left.push("politics: " + v.t); seen.set(v.id, null); continue; }
    const theme = (RULES.find(([, re]) => re.test(v.t)) || [pl.theme])[0];
    seen.set(v.id, { theme, v: { id: v.id, t: clean(v.t), d: v.d, c: pl.c } });
  }
  console.log(`  ${String(list.length).padStart(3)}  ${FR_CHANNELS[pl.c].name} – ${pl.t}`);
}

const themes = Object.fromEntries(FR_THEME_KEYS.map(k => [k, []]));
for (const x of seen.values()) if (x) themes[x.theme].push(x.v);
const total = Object.values(themes).reduce((n, l) => n + l.length, 0);
writeLibrary(OUT, `// Generated by scripts/pull-french.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// ${total} videos from ${Object.keys(FR_CHANNELS).length} advanced-level French channels, one theme each; c = channel key (src/frenchSources.js).
// Left out: ${left.length} (videos from other channels saved in the playlists, and partisan politics).`, themes);
console.log(`${total} videos in ${FR_THEME_KEYS.length} themes → src/frenchVideos.js`);
FR_THEME_KEYS.forEach(k => console.log(`  ${k.padEnd(14)} ${themes[k].length}`));
if (left.length) console.log("Left out:\n  " + left.join("\n  "));
